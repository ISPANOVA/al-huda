"""Brings the reviewed photos of the reciter-photos-results branch into the
app and the website.

  python3 tool/reciters/apply_results.py <clone of reciter-photos-results>

Copies <key>.jpg to assets/reciters and tool/lite/site/img/reciters, writes
lib/features/media/reciter_photos.dart and tool/lite/site/js/reciters.js
from credits.json, then redraws the Android Auto art.
"""
import json
import os
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = sys.argv[1]


def dart_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'


def main():
    credits = json.load(open(os.path.join(SRC, "credits.json"), encoding="utf-8"))
    credits = {k: v for k, v in credits.items() if os.path.exists(os.path.join(SRC, f"{k}.jpg"))}
    keys = sorted(credits)
    for d in ("assets/reciters", "tool/lite/site/img/reciters"):
        dest = os.path.join(ROOT, d)
        os.makedirs(dest, exist_ok=True)
        for f in os.listdir(dest):
            if f.endswith(".jpg") and f[:-4] not in credits:
                os.remove(os.path.join(dest, f))
        for k in keys:
            shutil.copyfile(os.path.join(SRC, f"{k}.jpg"), os.path.join(dest, f"{k}.jpg"))

    lines = [
        "// Generated by tool/reciters/apply_results.py from the photos of",
        "// tool/reciters/fetch_photos.py (Wikimedia Commons, free licences).",
        "// Reciters not listed keep their drawn monogram.",
        "",
        "/// Reciters with a portrait in assets/reciters/<key>.jpg.",
        "const kReciterPhotos = <String>{" + ", ".join(f"'{k}'" for k in keys) + "};",
        "",
        "/// Where each portrait comes from (shown on the sources page).",
        "const kReciterPhotoCredits = <({String name, String author, String license, String source})>[",
    ]
    for k in keys:
        c = credits[k]
        lines.append(f"  (name: {dart_str(c['name'])}, author: {dart_str(c['author'] or 'مؤلف غير معروف')}, "
                     f"license: {dart_str(c['license'])}, source: {dart_str(c['source'])}),")
    lines.append("];")
    text = "صور القراء من ويكيميديا كومنز برخص حرة، لكل صورة صاحبها ورخصتها: " + "، ".join(
        f"{credits[k]['name']}: {credits[k]['author'] or 'مؤلف غير معروف'} ({credits[k]['license']})" for k in keys
    ) + ". باقي القراء بلا صورة حرة، فيظهر لهم رسم بدلًا منها."
    lines += ["", "/// The same credits as one paragraph (the sources page).", f"const kReciterPhotoCreditsText = {dart_str(text)};", ""]
    open(os.path.join(ROOT, "lib/features/media/reciter_photos.dart"), "w", encoding="utf-8").write("\n".join(lines))

    js = ("// Reciters with a freely licensed portrait (Wikimedia Commons), and credits.\n"
          "// Generated by tool/reciters/apply_results.py.\n"
          f"export const CREDITS = {json.dumps({k: credits[k] for k in keys}, ensure_ascii=False)};\n"
          "export const PHOTOS = new Set(Object.keys(CREDITS));\n")
    open(os.path.join(ROOT, "tool/lite/site/js/reciters.js"), "w", encoding="utf-8").write(js)
    subprocess.check_call([sys.executable, os.path.join(ROOT, "tool/car/make_car_art.py")])
    print(len(keys), "photos:", " ".join(keys))


main()
