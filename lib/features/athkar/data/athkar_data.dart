/// Authentic athkar from Hisn Al-Muslim (حصن المسلم) with their sources.
class Thikr {
  final String id;
  final String text;
  final int count;
  final String source;
  final String? virtue;

  /// When set, the thikr is Quranic and can be recited with audio.
  final ({int surah, int from, int to})? quran;

  const Thikr({
    required this.id,
    required this.text,
    required this.count,
    required this.source,
    this.virtue,
    this.quran,
  });
}

class AthkarCategory {
  final String id;
  final String title;
  final String subtitle;
  final String emoji;
  final List<Thikr> items;

  const AthkarCategory({
    required this.id,
    required this.title,
    required this.subtitle,
    required this.emoji,
    required this.items,
  });
}

